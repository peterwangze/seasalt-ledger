export function Icon({
  name,
  size = 20,
  strokeWidth = 1.8,
  className,
  style,
}: {
  name: string;
  size?: number;
  strokeWidth?: number;
  className?: string;
  style?: React.CSSProperties;
}) {
  const Component = ICONS[name] ?? Tag;
  return <Component size={size} strokeWidth={strokeWidth} className={className} style={style} aria-hidden="true" />;
}

